// POST multipart/form-data: file, title, description (optional)
import { serve, fail, json } from '../_shared/http.ts'
import { requireActor } from '../_shared/auth.ts'
import { audit } from '../_shared/audit.ts'
import { DOC_COLUMNS } from '../_shared/documents.ts'
import { MAX_FILE_BYTES, detectFileType, sanitizeFilename, validateDescription, validateTitle } from '../_shared/validate.ts'

serve('upload-document', async (ctx) => {
  // 1. Who is calling? (verified token, not request body)
  const auth = await requireActor(ctx, 'document.upload')
  if (!auth.ok) return auth.response
  const actor = auth.actor

  // 2. Is this account type allowed to upload?
  if (actor.role === 'viewer') {
    await audit(ctx, actor, { action: 'document.upload', outcome: 'denied', details: { reason: 'viewer_role' } })
    return fail(ctx, 403, 'forbidden', 'Your account role cannot upload documents.')
  }

  // 3. Cheap size check BEFORE reading the body into memory.
  const declared = Number(ctx.req.headers.get('content-length') ?? '0')
  if (declared > MAX_FILE_BYTES + 100_000) {
    await audit(ctx, actor, { action: 'document.upload', outcome: 'failure', details: { reason: 'too_large' } })
    return fail(ctx, 413, 'too_large', 'File is larger than 5 MB.')
  }

  let form: FormData
  try {
    form = await ctx.req.formData()
  } catch {
    return fail(ctx, 400, 'bad_request', 'Expected a multipart form with a file.')
  }
  const file = form.get('file')
  if (!(file instanceof File)) return fail(ctx, 400, 'bad_request', 'A file is required.')
  if (file.size === 0) return fail(ctx, 400, 'bad_request', 'The file is empty.')
  if (file.size > MAX_FILE_BYTES) {
    await audit(ctx, actor, { action: 'document.upload', outcome: 'failure', details: { reason: 'too_large', size_bytes: file.size } })
    return fail(ctx, 413, 'too_large', 'File is larger than 5 MB.')
  }

  // 4. Server-side file signature check (the browser's checks are only for convenience).
  const bytes = new Uint8Array(await file.arrayBuffer())
  const detected = detectFileType(bytes)
  if (!detected) {
    await audit(ctx, actor, { action: 'document.upload', outcome: 'failure', details: { reason: 'unsupported_signature' } })
    return fail(ctx, 415, 'unsupported_type', 'Only PDF, PNG and JPEG files are allowed.')
  }
  if (file.type && file.type !== detected.mime) {
    await audit(ctx, actor, { action: 'document.upload', outcome: 'failure', details: { reason: 'declared_type_mismatch', detected: detected.mime } })
    return fail(ctx, 415, 'unsupported_type', 'The file content does not match its declared type.')
  }

  // 5. Validate the text fields.
  const title = validateTitle(form.get('title'))
  if (!title.ok) return fail(ctx, 400, 'invalid_input', title.error)
  const description = validateDescription(form.get('description'))
  if (!description.ok) return fail(ctx, 400, 'invalid_input', description.error)

  // 6. Store the bytes in the PRIVATE bucket. The path is generated by us (never from the
  //    user's file name), so there is no path traversal or overwriting someone else's file.
  const sha256 = Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', bytes)))
    .map((b) => b.toString(16).padStart(2, '0')).join('')
  const storagePath = `${actor.id}/${crypto.randomUUID()}`
  const up = await ctx.admin.storage.from('documents').upload(storagePath, bytes, { contentType: detected.mime, upsert: false })
  if (up.error) {
    console.error('storage upload failed', up.error)
    await audit(ctx, actor, { action: 'document.upload', outcome: 'failure', details: { reason: 'storage_error' } })
    return fail(ctx, 500, 'upload_failed', 'Upload failed.')
  }

  // 7. Record the metadata. If that fails, remove the orphaned file.
  const { data: doc, error } = await ctx.admin.from('documents').insert({
    owner_id: actor.id,
    owner_email: actor.email,
    title: title.value,
    description: description.value,
    original_filename: sanitizeFilename(file.name),
    mime_type: detected.mime,
    size_bytes: bytes.length,
    sha256,
    storage_path: storagePath,
  }).select(DOC_COLUMNS).single()
  if (error || !doc) {
    console.error('document insert failed', error)
    await ctx.admin.storage.from('documents').remove([storagePath])
    await audit(ctx, actor, { action: 'document.upload', outcome: 'failure', details: { reason: 'db_error' } })
    return fail(ctx, 500, 'upload_failed', 'Upload failed.')
  }

  await audit(ctx, actor, {
    action: 'document.upload', outcome: 'success', documentId: doc.id,
    details: { size_bytes: bytes.length, mime_type: detected.mime },
  })
  return json(ctx, { document: doc }, 201)
})
